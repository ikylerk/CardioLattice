export function tReport(key, vars) {
  const text = dictionaries[getLang()]?.[key] ?? dictionaries.en[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => vars?.[name] == null ? '' : String(vars[name]))
}
