function readStoredLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored === 'zh' || stored === 'en') return stored
  } catch {
    // Private mode or a file:// page may block storage.
  }
  return 'en'
}

let currentLang = readStoredLang()
const listeners = new Set()

function lookup(language, key) {
  const dict = dictionaries[language]
  if (!dict) return undefined
  let node = dict
  for (const part of key.split('.')) {
    if (node && typeof node === 'object' && Object.prototype.hasOwnProperty.call(node, part)) {
      node = node[part]
    } else {
      return undefined
    }
  }
  return typeof node === 'string' ? node : undefined
}

function interpolate(text, vars) {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? '' : String(vars[name])))
}

export function getLang() {
  return currentLang
}

// `en` or `zh`. Callers attach this as a `lang` query/body field on the request
// that drafts a report. It is not an Accept-Language header.
export function requestLang() {
  return currentLang === 'zh' ? 'zh' : 'en'
}

export function applyDocumentLang(language = currentLang) {
  if (typeof document === 'undefined') return
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en'
  const title = lookup(language, 'app.title')
  if (title) document.title = title
  const description = lookup(language, 'app.description')
  const meta = document.querySelector('meta[name="description"]')
  if (meta && description) meta.setAttribute('content', description)
}

export function setLang(language) {
  const next = language === 'zh' ? 'zh' : 'en'
  currentLang = next
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    // Ignore storage failures; the in-memory choice still applies.
  }
  applyDocumentLang(next)
  listeners.forEach((listener) => listener(next))
}

export function subscribeLang(listener) {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

export function t(key, vars) {
  const text = lookup(currentLang, key) ?? lookup('en', key) ?? key
  return interpolate(text, vars)
}

export function enumLabel(group, code) {
  if (!code) return ''
  const key = `${group}.${code}`
  return lookup(currentLang, key) ?? lookup('en', key) ?? String(code)
}

const UNKNOWN_ERROR = 'Unknown error'
// Published API codes are UPPER_SNAKE. A token with that shape is always a code:
// translate known codes; preserve unknown research identifiers for traceability.
const CODE_TOKEN = /^[A-Z][A-Z0-9_]*$/

function formatParam(value) {
  if (value == null) return ''
  if (Array.isArray(value)) return value.map((item) => formatParam(item)).join('×')
  if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') return String(value)
  return serverText(value)
}

function translateCode(code, params) {
  const template = lookup(requestLang(), `codes.${code}`) ?? lookup('en', `codes.${code}`)
  if (!template) return String(code)
  const vars = params && typeof params === 'object'
    ? Object.fromEntries(Object.entries(params).map(([key, item]) => [key, formatParam(item)]))
    : undefined
  return interpolate(template, vars)
}

// Server text is `{ code, params }` (`params` may be empty). A missing code falls
// back to English, then the stable identifier. Unknown research evidence is preserved.
// A string that is not a code token is an old database value the backend returned
// unchanged; that prose is shown as-is. Stored report prose does not come through here.
export function serverText(value) {
  if (value == null || value === '') return ''
  if (Array.isArray(value)) return value.map((item) => serverText(item)).filter(Boolean).join(' ')
  if (typeof value === 'object') {
    if (typeof value.code === 'string') return translateCode(value.code, value.params)
    if (value.detail != null && value.detail !== value) return serverText(value.detail)
    return UNKNOWN_ERROR
  }
  if (typeof value !== 'string') return UNKNOWN_ERROR
  if (CODE_TOKEN.test(value)) return translateCode(value)
  return value
}

export function measurementLabel(item) {
  if (!item) return ''
  if (item.label != null && item.label !== '') return serverText(item.label)
  if (item.code) return serverText({ code: item.code, params: {} })
  return ''
}

export function dicomLabel(text) {
  if (text == null || text === '') return ''
  return `${t('dicom.prefix')} ${text}`
}

export function errorDetail(err) {
  if (err == null) return ''
  if (typeof err === 'string') return err
  if (err.detail != null) return err.detail
  return err.message || String(err)
}

